/** Translates only static HTML text nodes; user-entered values and code are left untouched. */
export function localizeAdminText(text: string, locale: AdminLocale): string {
  if (locale !== 'en-US') return text;
  const exact = ENGLISH[text];
  if (exact) return exact;
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^无效的(分类|标签) ID。$/, (match) => `Invalid ${match[1] === '分类' ? 'category' : 'tag'} ID.`],
    [/^无效的(分类|标签)名称或缩略名。$/, (match) => `Invalid ${match[1] === '分类' ? 'category' : 'tag'} name or slug.`],
    [/^(分类|标签)名称不能为空、包含特殊字符或超过 150 字。$/, (match) => `${match[1] === '分类' ? 'Category' : 'Tag'} name is required, must not contain special characters, and must be 150 characters or fewer.`],
    [/^(分类|标签)缩略名无效或超过 128 字。$/, (match) => `Invalid ${match[1] === '分类' ? 'category' : 'tag'} slug or exceeds 128 characters.`],
    [/^(分类|标签)不存在。$/, (match) => `${match[1] === '分类' ? 'Category' : 'Tag'} not found.`],
    [/^(分类|标签)名称已经存在。$/, (match) => `This ${match[1] === '分类' ? 'category' : 'tag'} name already exists.`],
    [/^页面 (\d+)$/, (match) => `Page ${match[1]}`],
    [/^(\d+) 个子分类$/, (match) => `${match[1]} subcategories`],
    [/^(.+) 的子分类$/, (match) => `${match[1]} subcategories`],
  ];
  for (const [pattern, translate] of patterns) {
    const match = text.match(pattern);
    if (match) return translate(match);
  }
  return text;
}

export function localizeAdminHtml(html: string, locale: AdminLocale): string {
  if (locale !== 'en-US') return html;
  const chunks = html.split(/(<script\b[^>]*>[\s\S]*?<\/script\s*>|<style\b[^>]*>[\s\S]*?<\/style\s*>)/gi);
  const translated = chunks.map((chunk, index) => {
    if (index % 2 === 1) return chunk;
    return chunk.replace(/>([^<>]+)</g, (match, text: string) => {
      const leading = /^\s*/.exec(text)?.[0] ?? '';
      const trailing = /\s*$/.exec(text)?.[0] ?? '';
      const key = text.trim();
      const value = localizeAdminText(key, locale);
      return value !== key ? `>${leading}${value}${trailing}<` : match;
    });
  }).join('');
  const withAttributes = translated.replace(/\b(placeholder|aria-label|title|alt|data-uploading-label|data-empty-label)=(['"])(.*?)\2/gi, (match, name: string, quote: string, value: string) => {
    const localizedValue = localizeAdminText(value, locale);
    return localizedValue !== value ? `${name}=${quote}${localizedValue}${quote}` : match;
  }).replace(/confirm\((['"])([^'"]+)\1\)/g, (match, quote: string, value: string) => {
    const localizedValue = localizeAdminText(value, locale);
    return localizedValue !== value ? `confirm(${quote}${localizedValue}${quote})` : match;
  });
  return withAttributes
    .replace(/\blang=(['"])zh-CN\1/gi, 'lang="en-US"')
    .replace(/<title>([^<]*)<\/title>/i, (match, title: string) => {
      const suffix = ' · Typecho';
      const key = title.endsWith(suffix) ? title.slice(0, -suffix.length) : title;
      const value = localizeAdminText(key, locale);
      return value !== key ? `<title>${value}${suffix}</title>` : match;
    });
}
