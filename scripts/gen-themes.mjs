// Generates src/generated/themes.ts from themes/**/*.php so theme templates
// can be bundled into the worker without relying on a ".php?raw" loader.
import { readdirSync, readFileSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'themes');
const out = join(root, 'src', 'generated', 'themes.ts');

function walk(dir, base = '') {
  const files = {};
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = base ? `${base}/${name}` : name;
    if (statSync(full).isDirectory()) {
      Object.assign(files, walk(full, rel));
    } else if (name.endsWith('.php')) {
      files[rel] = readFileSync(full, 'utf8');
    }
  }
  return files;
}

const themes = {};
for (const name of readdirSync(src)) {
  const dir = join(src, name);
  if (!statSync(dir).isDirectory()) continue;
  themes[name] = walk(dir);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-themes.mjs - do not edit.\nexport const THEME_SOURCES: Record<string, Record<string, string>> = ${JSON.stringify(
    themes,
    null,
    2
  )};\n`,
  'utf8'
);

console.log(`generated ${Object.keys(themes).length} themes -> src/generated/themes.ts`);
