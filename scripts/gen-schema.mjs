// Generates src/generated/schema.ts from migrations/*.sql so a fresh database
// can be created by the worker itself (Typecho-style installer) instead of
// requiring `wrangler d1 migrations apply` before the first request.
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrations = join(root, 'migrations');
const out = join(root, 'src', 'generated', 'schema.ts');

const files = readdirSync(migrations).filter((name) => name.endsWith('.sql')).sort();
const statements = [];
for (const file of files) {
  const sql = readFileSync(join(migrations, file), 'utf8')
    .split('\n')
    .filter((line) => !line.trimStart().startsWith('--'))
    .join('\n');
  for (const chunk of sql.split(';')) {
    const statement = chunk.trim();
    if (statement) statements.push(statement);
  }
}

const tables = [];
for (const statement of statements) {
  const match = /^CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+([A-Za-z0-9_]+)/i.exec(statement);
  if (match) tables.push(match[1]);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-schema.mjs - do not edit.\n` +
    `// Statements come from ${files.join(', ')} and are idempotent (IF NOT EXISTS).\n` +
    `export const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};\n\n` +
    `export const SCHEMA_TABLES: string[] = ${JSON.stringify(tables, null, 2)};\n`,
  'utf8'
);

console.log(`generated ${statements.length} statements / ${tables.length} tables -> src/generated/schema.ts`);
